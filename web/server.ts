const DIRECTIONS = new Set(["N", "NE", "E", "SE", "S", "SW", "W", "NW"]);

const CURVE_ID = /^(\d{3})-\d{1,7}-\d{1,7}$/;

interface PassBody {
  curve_id: string;
  direction: string;
  speed_band_mph: number;
  hour_bucket: number;
  app_version: string;
}

function countyPrefix(county: string): string | null {
  const name = county.toLowerCase().replace(/-/g, " ");
  // Own keys only: "constructor" and "__proto__" are not counties.
  return Object.hasOwn(COUNTY_FIPS, name) ? `${COUNTY_FIPS[name]}-` : null;
}

function isArkansasCurveID(id: string): boolean {
  const county = Number(id.slice(0, 3));
  return county >= 1 && county <= 149 && county % 2 === 1;
}

function isPass(value: unknown): value is PassBody {
  if (typeof value !== "object" || value === null) return false;
  const row = value as Record<string, unknown>;
  return (
    typeof row.curve_id === "string" &&
    CURVE_ID.test(row.curve_id) &&
    isArkansasCurveID(row.curve_id) &&
    typeof row.direction === "string" &&
    DIRECTIONS.has(row.direction) &&
    typeof row.speed_band_mph === "number" &&
    Number.isFinite(row.speed_band_mph) &&
    row.speed_band_mph >= 0 &&
    row.speed_band_mph <= 150 &&
    Number.isInteger(row.hour_bucket) &&
    (row.hour_bucket as number) >= 0 &&
    (row.hour_bucket as number) <= 23 &&
    typeof row.app_version === "string" &&
    row.app_version.length >= 1 &&
    row.app_version.length <= 32
  );
}

function database(): Sql | null {
  const url = process.env.DATABASE_URL ?? process.env.POSTGRES_URL;
  if (!url) return null;
  return neon(url);
}

let schemaReady: Promise<void> | null = null;

function ensureSchema(sql: Sql): Promise<void> {
  schemaReady ??= (async () => {
    try {
      await sql.query(`
        CREATE TABLE IF NOT EXISTS passes (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          curve_id TEXT NOT NULL,
          direction TEXT NOT NULL,
          speed_band_mph DOUBLE PRECISION NOT NULL,
          hour_bucket INTEGER NOT NULL,
          app_version TEXT NOT NULL,
          created_at TIMESTAMPTZ NOT NULL DEFAULT now()
        )
      `);
      await sql.query(`CREATE INDEX IF NOT EXISTS passes_curve ON passes (curve_id)`);
      await sql.query(
        `ALTER TABLE passes ALTER COLUMN speed_band_mph TYPE DOUBLE PRECISION USING speed_band_mph::double precision`,
      );
    } catch (error) {
      schemaReady = null;
      throw error;
    }
  })();
  return schemaReady;
}

app.get("/api/health", (c) => c.json({ ok: true }));

app.post("/api/pass", async (c) => {
  const client = database();
  if (!client) return c.json({ error: "database unavailable" }, 503);
  let body: unknown;
  try {
    body = await c.req.json();
  } catch {
    return c.json({ error: "invalid json" }, 400);
  }
  if (!isPass(body)) return c.json({ error: "missing fields" }, 400);
  await ensureSchema(client);
  await client.query(
    // The day is enough for the rolling export. A full timestamp plus the order of arrival
    // could be used to follow one phone along a drive.
    `INSERT INTO passes (curve_id, direction, speed_band_mph, hour_bucket, app_version, created_at)
     VALUES ($1, $2, $3, $4, $5, date_trunc('day', now()))`,
    [
      body.curve_id,
      body.direction,
      body.speed_band_mph,
      body.hour_bucket,
      body.app_version,
    ],
  );
  return c.json({ stored: true });
});

app.get("/api/export/:file", async (c) => {
  let county: string;
  try {
    county = decodeURIComponent(c.req.param("file")).replace(/\.csv$/, "");
  } catch {
    return c.json({ error: "unknown county" }, 404);
  }
  const prefix = countyPrefix(county);
  if (prefix === null) return c.json({ error: "unknown county" }, 404);
  const client = database();
  if (!client) {
    return c.text("curve_id,n,hour_buckets\n", 200, {
      "content-type": "text/csv; charset=utf-8",
    });
  }
  await ensureSchema(client);
  const rows = await client.query(
    `SELECT curve_id,
            COUNT(*)::int AS n,
            COUNT(DISTINCT hour_bucket)::int AS hours
     FROM passes
     WHERE curve_id LIKE $1
     GROUP BY curve_id
     ORDER BY curve_id`,
    [`${prefix}%`],
  );
  const lines = ["curve_id,n,hour_buckets"];
  for (const row of rows) {
    lines.push(`${row.curve_id},${row.n},${row.hours}`);
  }
  return c.text(lines.join("\n") + "\n", 200, {
    "content-type": "text/csv; charset=utf-8",
  });
});

